"""Phase 11: write results/REPORT.md purely from the result files (no numbers typed by hand)."""
import json

import numpy as np
import pandas as pd

import _common  # noqa: F401

from naf.config import load_config, repo_path

NAMES = {"logreg": "LogReg", "rf": "RF", "xgb": "XGBoost", "baseline_random": "Random (baseline)",
         "baseline_anomaly": "Anomaly (baseline)"}


def md(df: pd.DataFrame) -> str:
    cols = list(df.columns)
    lines = ["| " + " | ".join(map(str, cols)) + " |", "|" + "---|" * len(cols)]
    for _, r in df.iterrows():
        lines.append("| " + " | ".join("" if (isinstance(v, float) and np.isnan(v)) else str(v) for v in r) + " |")
    return "\n".join(lines)


def ci(v, lo, hi, pct=False, nd=2):
    if pd.isna(v):
        return "—"
    f = (lambda x: f"{100 * x:.0f}%") if pct else (lambda x: f"{x:.{nd}f}")
    return f(v) if pd.isna(lo) else f"{f(v)} [{f(lo)}, {f(hi)}]"


def table(s: pd.DataFrame, extra=()) -> pd.DataFrame:
    out = pd.DataFrame({
        **{e: s[e].values for e in extra},
        "model": s["model"].map(NAMES).values, "alerter": s["alerter"].values, "seeds": s["n_seeds"].values,
        "onsets": s["n_onsets"].values, "warned (mean)": s["warned_mean"].round(1).values,
        "detection [95% boot]": [ci(a, b, c, True) for a, b, c in zip(s.detection, s.det_boot_lo, s.det_boot_hi)],
        "lead min [95%]": [ci(a, b, c, nd=1) for a, b, c in zip(s.mean_lead_min, s.lead_lo, s.lead_hi)],
        "FA/hour [95%]": [ci(a, b, c) for a, b, c in zip(s.fa_per_hour, s.fa_lo, s.fa_hi)],
        "PR-AUC": s["pr_auc_mean"].round(3).values, "pos. rate": s["positive_rate"].round(3).values})
    return out


def main():
    cfg = load_config()
    r = repo_path(cfg, "results_dir")
    info = json.loads((r / "run_info.json").read_text())
    gate = json.loads((r / "power_gate.json").read_text())
    prim = pd.read_csv(r / "summary_primary.csv")
    fold = pd.read_csv(r / "summary_per_fold.csv")
    fam = pd.read_csv(r / "family_events.csv")
    parts = [f"# Experimental results (generated by scripts/06_report.py)\n",
             f"Config hash `{info['config_hash']}` · H = {info['H']} min · G = {info['G']} min · "
             f"false-alarm budget {info['fa_target_per_hour']}/hour · primary folds {', '.join(info['primary_folds'])}.\n",
             "Intervals: detection = event-cluster bootstrap (seeds averaged per draw); FA/hour = 60-minute "
             "block bootstrap; lead = bootstrap over onsets. 'warned (mean)' is the number of onsets warned, "
             "averaged over seeds.\n",
             "## Power gate\n",
             md(pd.DataFrame([{"fold": f, "role": g["role"], "test day": g["test_day"],
                               "train pos": g["train"]["positives"], "train onsets": g["train"]["onsets_with_positive_minutes"],
                               "calib onsets": g["calib"]["onsets_with_positive_minutes"],
                               "test onsets": g["test"]["onsets_with_positive_minutes"]} for f, g in gate.items()])),
             "\n## Primary results (F1 + F2 pooled)\n", md(table(prim)),
             "\n## Per fold\n", md(table(fold, extra=("folds",))),
             "\n## Per onset — share of seeds warned (static conformal)\n"]
    f = fam[fam.alerter == "conformal"].pivot_table(index=["fold", "onset_id", "family"], columns="model",
                                                     values="warned_frac").reset_index().round(2)
    parts.append(md(f))
    for name, title in [("sensitivity.csv", "Sensitivity (G, H) — primary folds"),
                        ("ablation_no_monday.csv", "Day-identity control: no Monday in training"),
                        ("lodo_summary.csv", "Leave-one-day-out (NON-chronological diagnostic)")]:
        p = r / name
        if p.exists():
            s = pd.read_csv(p)
            extra = ("G", "H") if "G" in s.columns else ()
            if extra:
                s = s[s.alerter == "conformal"]
            parts += [f"\n## {title}\n", md(table(s, extra=extra))]
    p = r / "lodo_family_events.csv"
    if p.exists():
        lf = pd.read_csv(p)
        parts += ["\n## Leave-one-day-out per onset — share of seeds warned (static conformal)\n",
                  md(lf[lf.alerter == "conformal"].pivot_table(index=["fold", "onset_id", "family"], columns="model",
                                                                values="warned_frac").reset_index().round(2))]
    # Sanity check: do the scores react to attacks at all? (detection, not forecasting)
    mins = pd.read_parquet(r / "minutes.parquet")
    mm = mins[(mins.variant == "forward") & mins.fold.isin(info["primary_folds"]) & (mins.alerter == "conformal")].copy()
    mm["group"] = np.where(mm.status == "ongoing",
                           np.where(mm.n_attack_flows > 0, "ongoing: attack-active minute", "ongoing: gap/cool-down"),
                           np.where(mm.status == "eligible", np.where(mm.y == 1, "eligible: pre-onset (y=1)", "eligible: quiet (y=0)"),
                                    "ambiguous"))
    sc = mm.groupby(["model", "group"]).agg(minutes=("score", "size"), median_score=("score", "median"),
                                            exceed_rate=("exceed", "mean")).reset_index()
    sc["minutes"] = (sc["minutes"] / mm.groupby("model")["seed"].transform("nunique").groupby(mm["model"]).first()
                     .reindex(sc["model"]).values).round().astype(int)
    parts += ["\n## Forecast scores by minute type (primary test days, static conformal; minutes per seed)\n",
              "Forecasting models were trained only on eligible minutes (ongoing attacks excluded by design), so "
              "they are not expected to score running attacks high. Whether the features can see attacks at all is "
              "tested separately by the detection diagnostic below.\n",
              md(sc.round(4))]
    p = r / "detection_check_runs.csv"
    if p.exists():
        dr = pd.read_csv(p).groupby(["fold", "model"])[["roc_auc", "pr_auc", "attack_rate", "recall_at_budget",
                                                       "quiet_exceed_rate"]].mean().round(3).reset_index()
        de = pd.read_csv(r / "detection_check_events.csv")
        dp = de.groupby(["fold", "onset_id", "family", "model"]).agg(det=("detected", "mean"), delay=("delay_min", "mean"))
        dp = dp.unstack("model").round(2)
        dp.columns = [f"{a}_{b}" for a, b in dp.columns]
        parts += ["\n## Diagnostic: DETECTION of running attacks with the same features (scripts/05b)\n",
                  "Target: attack flow started in the previous 3 minutes vs quiet minutes; same folds, models and "
                  "static-conformal threshold. Recall/exceedance are per minute.\n", md(dr),
                  "\nPer campaign: share of seeds detecting it, and mean delay (minutes after onset) to the first exceedance.\n",
                  md(dp.reset_index())]
    p = r / "drift.csv"
    if p.exists():
        d = pd.read_csv(p)
        g = d[d.alerter == "conformal"].groupby(["fold", "model"])["test_quiet_exceed_rate"].mean().unstack()
        parts += ["\n## Drift: realised quiet-minute exceedance rate on the test day (target "
                  f"{d.target_exceed_rate.iloc[0]:.4f}), static conformal\n", md(g.round(4).reset_index())]
    (r / "REPORT.md").write_text("\n".join(parts) + "\n", encoding="utf-8")
    print(f"wrote {r / 'REPORT.md'}")


if __name__ == "__main__":
    main()
